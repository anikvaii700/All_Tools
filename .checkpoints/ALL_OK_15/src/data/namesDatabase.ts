// Deterministic helper to generate a profile for ANY name
export function getOrCreateNameProfile(
  rawName: string,
  userOrigin?: string,
  userGender?: 'male' | 'female' | 'unisex' | 'prefer-not-to-say',
  birthDate?: string
): NameEntry {
  const clean = rawName.trim();
  const lower = clean.toLowerCase();

  // 1. Direct or alias match
  for (const key of Object.keys(CURATED_NAMES_DATABASE)) {
    const item = CURATED_NAMES_DATABASE[key];
    if (key === clean || item.bangla === clean) {
      return adaptEntryForAge(fillEntryDefaults(item, clean), birthDate);
    }
    if (item.english?.toLowerCase() === lower) {
      return adaptEntryForAge(fillEntryDefaults(item, clean), birthDate);
    }
    if (item.aliases?.some((a) => a.toLowerCase() === lower || a === clean)) {
      return adaptEntryForAge(fillEntryDefaults(item, clean), birthDate);
    }
  }

  // 2. Intelligent multi-word and compound name matching
  const words = clean.split(/\s+/).filter(Boolean);
  if (words.length > 1) {
    // Check if compound name matches components
    const contentWords = words.filter((w) => !COMMON_TITLES.has(w.toLowerCase()) && !COMMON_TITLES.has(w));
    
    // Look up content words
    const matchedItems: Array<{ word: string; item: Partial<NameEntry> }> = [];
    for (const w of (contentWords.length > 0 ? contentWords : words)) {
      const wLow = w.toLowerCase();
      for (const key of Object.keys(CURATED_NAMES_DATABASE)) {
        const item = CURATED_NAMES_DATABASE[key];
        if (key === w || item.bangla === w || item.english?.toLowerCase() === wLow || item.aliases?.some((a) => a.toLowerCase() === wLow || a === w)) {
          matchedItems.push({ word: w, item });
          break;
        }
      }
    }

    if (matchedItems.length >= 2) {
      // Compound synthesis (e.g. Afifa + Jannat)
      const first = matchedItems[0].item;
      const second = matchedItems[1].item;
      const combinedMeaning = `${first.meaning?.replace(/[।\s]+$/, '')} এবং ${second.meaning || ''}`.trim();
      const combinedEntry: Partial<NameEntry> = {
        bangla: clean,
        english: transliterateToEnglish(clean),
        meaning: combinedMeaning,
        origin: first.origin || second.origin || 'আরবি',
        gender: first.gender || second.gender || 'unisex',
        headline: `${first.headline || second.headline || 'মর্যাদাময়ী ও শুভ ব্যক্তিত্ব'}`,
        personalityCategory: first.personalityCategory || 'শান্ত ও ধৈর্যশীল',
        personalityDescription: first.personalityDescription || 'মার্জিত ব্যবহার ও সুন্দর মননের অধিকারী।',
        positiveTraits: first.positiveTraits || ['পবিত্র মন', 'মিষ্টি ব্যবহার', 'শালীনতা'],
        futurePossibilities: first.futurePossibilities || ['উচ্চশিক্ষা ও মানবিক সেবায় সমাজে পরম শ্রদ্ধার আসন।'],
        practicalAdvice: first.practicalAdvice || ['নিজের ভালো গুণাবলি ধরে রেখে আত্মবিশ্বাসের সাথে বড় হোন।'],
      };
      return adaptEntryForAge(fillEntryDefaults(combinedEntry, clean), birthDate);
    }

    if (matchedItems.length === 1) {
      // One content word matched (e.g. "আফিফা আক্তার" -> matches "আফিফা")
      return adaptEntryForAge(fillEntryDefaults(matchedItems[0].item, clean), birthDate);
    }
  }

  // 3. Fallback partial word match for any word in input
  for (const w of words) {
    const wLower = w.toLowerCase();
    for (const key of Object.keys(CURATED_NAMES_DATABASE)) {
      const item = CURATED_NAMES_DATABASE[key];
      if (key === w || item.bangla === w || item.english?.toLowerCase() === wLower) {
        return adaptEntryForAge(fillEntryDefaults(item, clean), birthDate);
      }
    }
  }

  // 4. Smart Root Semantic Detection for Islamic & Bengali names
  let rootMeaning = '';
  let rootOrigin: 'বাংলা' | 'আরবি' | 'ফারসি' | 'সংস্কৃত' | 'আধুনিক / মিশ্র' = 'বাংলা';

  if (clean.includes('নূর') || clean.includes('নুর') || lower.includes('noor') || lower.includes('nur')) {
    rootMeaning = 'আলো, জ্যোতি ও হেদায়েতের শুভ প্রতীক।';
    rootOrigin = 'আরবি';
  } else if (clean.includes('জান্নাত') || lower.includes('jannat')) {
    rootMeaning = 'জান্নাত, বেহেশত ও চিরস্থায়ী শান্তির উদ্যান।';
    rootOrigin = 'আরবি';
  } else if (clean.includes('রহমান') || lower.includes('rahman')) {
    rootMeaning = 'পরম করুণাময় ও দয়াময় আল্লাহর অসীম রহমত।';
    rootOrigin = 'আরবি';
  } else if (clean.includes('উদ্দীন') || clean.includes('উদ্দিন') || lower.includes('uddin')) {
    rootMeaning = 'ধর্মের আলোকবর্তিকা, সৌন্দর্য ও সম্মান।';
    rootOrigin = 'আরবি';
  } else if (clean.includes('উল্লাহ') || lower.includes('ullah')) {
    rootMeaning = 'আল্লাহর একনিষ্ঠ অনুগত বান্দা ও প্রিয়জন।';
    rootOrigin = 'আরবি';
  } else if (clean.includes('আফিফ') || lower.includes('afif')) {
    rootMeaning = 'পবিত্রতা, সাধুতা ও নিষ্কলুষ স্বভাবের প্রতীক।';
    rootOrigin = 'আরবি';
  } else if (clean.includes('আদিব') || lower.includes('adib')) {
    rootMeaning = 'সুশিক্ষা, জ্ঞানচর্চা ও মার্জিত শিষ্টাচার।';
    rootOrigin = 'আরবি';
  }

  // 5. Hash-based deterministic fallback for completely unique name
  let hash = 0;
  for (let i = 0; i < clean.length; i++) {
    hash = (hash << 5) - hash + clean.charCodeAt(i);
    hash |= 0;
  }
  const positiveHash = Math.abs(hash);
  const archetypeIdx = positiveHash % ARCHETYPES.length;
  const archetype = ARCHETYPES[archetypeIdx];

  const origins: Array<'বাংলা' | 'আরবি' | 'ফারসি' | 'সংস্কৃত' | 'আধুনিক / মিশ্র'> = [
    'বাংলা',
    'আরবি',
    'ফারসি',
    'সংস্কৃত',
    'আধুনিক / মিশ্র',
  ];
  const detectedOrigin = (userOrigin as any) || (rootMeaning ? rootOrigin : origins[positiveHash % origins.length]);

  const baseEntry: NameEntry = {
    bangla: clean,
    english: transliterateToEnglish(clean),
    meaning:
      rootMeaning ||
      'একটি সুন্দর ও অর্থবহ নাম। এর মূল ভাবার্থ শুভ সূচনা, মেধা ও আত্মমর্যাদার প্রতীক নির্দেশ করে।',
    origin: detectedOrigin,
    gender: userGender === 'prefer-not-to-say' ? 'unisex' : userGender || 'unisex',
    headline: `${archetype.headline} — এক বিশেষ নাম`,
    personalityCategory: archetype.category,
    personalityDescription: archetype.description,
    positiveTraits: archetype.positiveTraits,
    futurePossibilities: archetype.futurePossibilities,
    practicalAdvice: archetype.practicalAdvice,
  };

  return adaptEntryForAge(baseEntry, birthDate);
}

function fillEntryDefaults(item: Partial<NameEntry>, userTypedName: string): NameEntry {
  const matchedArchetype =
    ARCHETYPES.find((a) => a.category === item.personalityCategory) || ARCHETYPES[0];

  return {
    bangla: item.bangla || userTypedName,
    english: item.english || transliterateToEnglish(userTypedName),
    meaning: item.meaning || 'অর্থবহ ও সমৃদ্ধি নির্দেশক নাম।',
    origin: item.origin || 'বাংলা',
    gender: item.gender || 'unisex',
    headline: item.headline || matchedArchetype.headline,
    personalityCategory: item.personalityCategory || matchedArchetype.category,
    personalityDescription: item.personalityDescription || matchedArchetype.description,
    positiveTraits: item.positiveTraits || matchedArchetype.positiveTraits,
    futurePossibilities: item.futurePossibilities || matchedArchetype.futurePossibilities,
    practicalAdvice: item.practicalAdvice || matchedArchetype.practicalAdvice,
  };
}

export function transliterateToEnglish(name: string): string {
  // If it's already English/Latin
  if (/^[a-zA-Z\s]+$/.test(name)) {
    return name
      .split(' ')
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
      .join(' ');
  }

  // Simple phonetic map for Bengali letters to nice Romanized output
  const charMap: Record<string, string> = {
    'অ': 'O', 'আ': 'A', 'ই': 'I', 'ঈ': 'I', 'উ': 'U', 'ঊ': 'U', 'ঋ': 'R', 'এ': 'E', 'ঐ': 'Oi', 'ও': 'O', 'ঔ': 'Ou',
    'ক': 'k', 'খ': 'kh', 'গ': 'g', 'ঘ': 'gh', 'ঙ': 'ng',
    'চ': 'ch', 'ছ': 'chh', 'জ': 'j', 'ঝ': 'jh', 'ঞ': 'n',
    'ট': 't', 'ঠ': 'th', 'ড': 'd', 'ঢ': 'dh', 'ণ': 'n',
    'ত': 't', 'থ': 'th', 'দ': 'd', 'ধ': 'dh', 'ন': 'n',
    'প': 'p', 'ফ': 'f', 'ব': 'b', 'ভ': 'bh', 'ম': 'm',
    'য': 'y', 'র': 'r', 'ল': 'l', 'শ': 'sh', 'ষ': 'sh', 'স': 's', 'হ': 'h',
    'ড়': 'r', 'ঢ়': 'rh', 'য়': 'y',
    'া': 'a', 'ি': 'i', 'ী': 'i', 'ু': 'u', 'ূ': 'u', 'ৃ': 'ri', 'ে': 'e', 'ৈ': 'oi', 'ো': 'o', 'ৌ': 'ou',
    '্': '', 'ং': 'ng', 'ঃ': 'h', 'ঁ': '',
  };

  let res = '';
  for (const c of name) {
    if (charMap[c] !== undefined) {
      res += charMap[c];
    } else {
      res += c;
    }
  }

  const clean = res.trim();
  if (!clean) return name;
  return clean.charAt(0).toUpperCase() + clean.slice(1);
}
