export function calculateAge(birthDateStr: string): AgeDetails | null {
  if (!birthDateStr) return null;
  const parts = birthDateStr.split('-');
  if (parts.length !== 3) return null;
  const bYear = parseInt(parts[0], 10);
  const bMonth = parseInt(parts[1], 10);
  const bDay = parseInt(parts[2], 10);

  if (isNaN(bYear) || isNaN(bMonth) || isNaN(bDay)) return null;

  const now = new Date();
  const cYear = now.getFullYear();
  const cMonth = now.getMonth() + 1;
  const cDay = now.getDate();

  let years = cYear - bYear;
  let months = cMonth - bMonth;
  let days = cDay - bDay;

  if (days < 0) {
    months--;
    const prevMonthDays = new Date(cYear, cMonth - 1, 0).getDate();
    days += prevMonthDays;
  }

  if (months < 0) {
    years--;
    months += 12;
  }

  if (years < 0) return null;

  const toBn = (n: number) =>
    n.toString().replace(/\d/g, (d) => '০১২৩৪৫৬৭৮৯'[parseInt(d, 10)]);

  let stage: 'infant' | 'child' | 'school' | 'teen' | 'young_adult' | 'adult' | 'elder';
  let stageBn = '';

  if (years <= 3) {
    stage = 'infant';
    stageBn = 'আদুরে শিশু';
  } else if (years <= 8) {
    stage = 'child';
    stageBn = 'ছোট্ট সোনামণি';
  } else if (years <= 13) {
    stage = 'school';
    stageBn = 'স্কুল শিক্ষার্থী';
  } else if (years <= 19) {
    stage = 'teen';
    stageBn = 'কিশোর শিক্ষার্থী';
  } else if (years <= 35) {
    stage = 'young_adult';
    stageBn = 'উদ্যমী তরুণ';
  } else if (years < 60) {
    stage = 'adult';
    stageBn = 'অভিজ্ঞ ও দায়িত্বশীল';
  } else {
    stage = 'elder';
    stageBn = 'শ্রদ্ধেয় প্রবীণ';
  }

  let ageTextBn = '';
  if (years === 0) {
    if (months === 0) {
      ageTextBn = `${toBn(days)} দিন`;
    } else {
      ageTextBn = `${toBn(months)} মাস ${toBn(days)} দিন`;
    }
  } else {
    ageTextBn = `${toBn(years)} বছর${months > 0 ? ` ${toBn(months)} মাস` : ''}`;
  }

  return { years, months, days, stage, stageBn, ageTextBn };
}

export function calculateWesternZodiac(
  birthDateStr: string,
  stage?: string
): ZodiacInfo | null {
  if (!birthDateStr) return null;
  const parts = birthDateStr.split('-');
  if (parts.length !== 3) return null;
  const month = parseInt(parts[1], 10);
  const day = parseInt(parts[2], 10);

  if (isNaN(month) || isNaN(day)) return null;

  let baseZodiac: ZodiacInfo;

  if ((month === 3 && day >= 21) || (month === 4 && day <= 19)) {
    baseZodiac = ZODIAC_SIGNS[0]; // মেষ
  } else if ((month === 4 && day >= 20) || (month === 5 && day <= 20)) {
    baseZodiac = ZODIAC_SIGNS[1]; // বৃষ
  } else if ((month === 5 && day >= 21) || (month === 6 && day <= 20)) {
    baseZodiac = ZODIAC_SIGNS[2]; // মিথুন
  } else if ((month === 6 && day >= 21) || (month === 7 && day <= 22)) {
    baseZodiac = ZODIAC_SIGNS[3]; // কর্কট
  } else if ((month === 7 && day >= 23) || (month === 8 && day <= 22)) {
    baseZodiac = ZODIAC_SIGNS[4]; // সিংহ
  } else if ((month === 8 && day >= 23) || (month === 9 && day <= 22)) {
    baseZodiac = ZODIAC_SIGNS[5]; // কন্যা
  } else if ((month === 9 && day >= 23) || (month === 10 && day <= 22)) {
    baseZodiac = ZODIAC_SIGNS[6]; // তুলা
  } else if ((month === 10 && day >= 23) || (month === 11 && day <= 21)) {
    baseZodiac = ZODIAC_SIGNS[7]; // বৃশ্চিক
  } else if ((month === 11 && day >= 22) || (month === 12 && day <= 21)) {
    baseZodiac = ZODIAC_SIGNS[8]; // ধনু
  } else if ((month === 12 && day >= 22) || (month === 1 && day <= 19)) {
    baseZodiac = ZODIAC_SIGNS[9]; // মকর
  } else if ((month === 1 && day >= 20) || (month === 2 && day <= 18)) {
    baseZodiac = ZODIAC_SIGNS[10]; // কুম্ভ
  } else if ((month === 2 && day >= 19) || (month === 3 && day <= 20)) {
    baseZodiac = ZODIAC_SIGNS[11]; // মীন
  } else {
    baseZodiac = ZODIAC_SIGNS[0];
  }

  // If infant or young child, adapt to sweet child nature
  if (stage === 'infant' || stage === 'child') {
    return {
      ...baseZodiac,
      trait: baseZodiac.childTrait || baseZodiac.trait,
    };
  }

  return baseZodiac;
}

